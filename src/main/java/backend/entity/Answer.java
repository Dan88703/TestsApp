import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.util.UUID;

@Data
@Builder(toBuilder = true)
@AllArgsConstructor
@NoArgsConstructor
public class Answer {
    private UUID id;
    private String text;
    @JsonProperty("isCorrect")
    private boolean correct;
}
